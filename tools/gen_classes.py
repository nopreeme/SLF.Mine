NAMES = {j[0]: j[2] for j in JOBS}
APEX = {"berserker", "warlord", "sacred_star_ninja"}   # jobs that also play the challenge sound (they grant an apex title)


def J(o): return json.dumps(o, ensure_ascii=False, separators=(",", ":"))
def article(name): return "an" if name[0] in "AEIOU" else "a"
def write(rel, lines):
    p = os.path.join(FN, rel); os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "w", encoding="utf-8", newline="\n") as f: f.write("\n".join(lines) + "\n")


def grant(job):
    key, cid, name, jp, color, level, frm, skills, extra, hidden = job
    if not frm:   # a starting class
        head = ["execute if entity @s[tag=slf.class_chosen] run return fail", "tag @s add slf.class_chosen", "tag @s add slf.classes_v2"]
    else:
        head = ["execute " + " ".join(f"unless entity @s[tag=slf.was_{p}]" for p in frm) + " run return fail"]
    lines = [GENERATED] + head + [f"tag @s add slf.was_{key}", f"scoreboard players set @s slf.class {cid}"]
    if not frm: lines.append("scoreboard players set @s slf.level 1")
    lines += [f"tag @s add slf.skill.{s}" for s in skills] + extra
    if key in APEX: lines.append("playsound minecraft:ui.toast.challenge_complete master @s")
    lines.append("tellraw @s " + J({"text": f"You have become {article(name)} {name}.", "color": color, "bold": True}))
    if not frm: lines.append("function slf:class/select_cleanup")
    return lines


def main():
    for f in os.listdir(os.path.join(FN, "grant")): os.remove(os.path.join(FN, "grant", f))
    for job in JOBS: write(f"grant/{job[0]}.mcfunction", grant(job))
    menu = [GENERATED, "# Class evolution menu. Runs as the player. Shows every evolution open to their lineage;",
            "# requirements are enforced in class/evolve_apply (level) and class/grant/* (lineage).",
            "execute unless entity @s[tag=slf.class_chosen] run return run function slf:class/select",
            "scoreboard players enable @s slf.evolve",
            "tellraw @s " + J(["", {"text": "━━━ ", "color": "dark_gray"}, {"text": "Class Evolution", "color": "gold", "bold": True},
                              {"text": " ━━━", "color": "dark_gray"}, {"text": "\nYour level: ", "color": "gray"},
                              {"score": {"name": "@s", "objective": "slf.level"}, "color": "white"}]),
            "scoreboard players set #shown slf.tmp 0"]
    apply = [GENERATED, "# Runs as a player whose slf.evolve trigger is set to a class id. Checks the level requirement and",
             "# lineage, then hands over to the grant function.",
             "scoreboard players operation #id slf.tmp = @s slf.evolve", "scoreboard players reset @s slf.evolve",
             "execute unless entity @s[tag=slf.class_chosen] run return fail"]
    for key, cid, name, jp, color, level, frm, *_rest in JOBS:
        if level is None: continue
        hidden = _rest[-1]
        frm_names = " or ".join(NAMES[p] for p in frm)
        menu += ["scoreboard players set #ok slf.tmp 0"] + [f"execute if entity @s[tag=slf.was_{p}] run scoreboard players set #ok slf.tmp 1" for p in frm]
        menu += [f"execute if entity @s[tag=slf.was_{key}] run scoreboard players set #ok slf.tmp 0",
                 "execute if score #ok slf.tmp matches 1 run tellraw @s " + J([" ", {"text": f"[{name}]", "color": color,
                     "click_event": {"action": "run_command", "command": f"trigger slf.evolve set {cid}"},
                     "hover_event": {"action": "show_text", "value": f"{name}{f' ({jp})' if jp else ''}{' - a hidden job' if hidden else ''}. From {frm_names}, requires level {level}"}},
                     {"text": f"  level {level}+", "color": "gray"}]),
                 "execute if score #ok slf.tmp matches 1 run scoreboard players set #shown slf.tmp 1"]
        need = " ".join(f"unless entity @s[tag=slf.was_{p}]" for p in frm)
        apply += [f"# {name} ({cid})",
                  f"execute if score #id slf.tmp matches {cid} if entity @s[tag=slf.was_{key}] run return run tellraw @s " + J({"text": f"You are already {article(name)} {name}.", "color": "yellow"}),
                  f"execute if score #id slf.tmp matches {cid} {need} run return run tellraw @s " + J({"text": f"{name} is not on your path. It evolves from {frm_names}.", "color": "red"}),
                  f"execute if score #id slf.tmp matches {cid} unless score @s slf.level matches {level}.. run return run tellraw @s " +
                  J(["", {"text": f"{name} requires level {level}. You are level ", "color": "red"}, {"score": {"name": "@s", "objective": "slf.level"}, "color": "white"}, {"text": ".", "color": "red"}]),
                  f"execute if score #id slf.tmp matches {cid} run return run function slf:class/grant/{key}"]
    menu += ["# Knights pick Holy or Dark through the trials, not from this list",
             "execute if entity @s[tag=slf.was_knight,tag=!slf.was_holy_knight,tag=!slf.was_dark_knight] run tellraw @s " +
             J(["", {"text": " Knight Trials: ", "color": "gold"}, {"score": {"name": "@s", "objective": "slf.knight_trials"}, "color": "white"},
                {"text": "/3 - then choose Holy or Dark", "color": "gray"}]),
             "execute if entity @s[tag=slf.was_knight,tag=!slf.was_holy_knight,tag=!slf.was_dark_knight] run scoreboard players set #shown slf.tmp 1",
             "execute if score #shown slf.tmp matches 0 run tellraw @s " + J({"text": " Your current path has no further evolution.", "color": "gray"}),
             "tellraw @s " + J(["", {"text": "[Back]", "color": "dark_gray", "click_event": {"action": "run_command", "command": "trigger slf.menu set 1"},
                                "hover_event": {"action": "show_text", "value": "Main menu"}}])]
    write("evolve.mcfunction", menu)
    write("evolve_apply.mcfunction", apply)
    write("name.mcfunction", [GENERATED, "# The status sheet's class line, from the slf.class score."] +
          [f"execute if score @s slf.class matches {cid} run tellraw @s " + J(["", {"text": " Class: ", "color": "gray"}, {"text": name, "color": color, "bold": True}])
           for key, cid, name, jp, color, *_ in JOBS])
    print(f"{len(JOBS)} jobs")


if __name__ == "__main__":
    main()
