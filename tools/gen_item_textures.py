    images = {n: draw(n) for n in ITEMS}
    for n, im in images.items(): im.save(os.path.join(OUT, n + ".png"))
    print(f"wrote {len(images)} textures to {OUT}")
    if "--sheet" in sys.argv:
        cols, cell = 10, 16 * 6 + 12; names = list(images)
        sheet = Image.new("RGB", (cols * cell, ((len(names) + cols - 1) // cols) * cell), (139, 139, 139))
        for k, n in enumerate(names):
            x, y = (k % cols) * cell + 6, (k // cols) * cell + 6
            slot = Image.new("RGB", (96, 96), (85, 85, 85) if (k // cols) % 2 else (198, 198, 198))
            big = images[n].resize((96, 96), Image.NEAREST); slot.paste(big, (0, 0), big); sheet.paste(slot, (x, y))
        sheet.save(sys.argv[sys.argv.index("--sheet") + 1])
