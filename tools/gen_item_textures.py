def rgb(h, s, v): return tuple(int(round(x * 255)) for x in colorsys.hsv_to_rgb((h % 360) / 360, max(0, min(1, s)), max(0, min(1, v)))) + (255,)

def ramp(h, s, v):
    """Hue-shifted 5-tone ramp: shadows drift toward blue-violet and gain saturation, highlights drift warm and pale."""
    return {"O": rgb(h - 24, s * 0.9 + 0.1, v * 0.20), "D": rgb(h - 14, s * 1.05, v * 0.48), "M": rgb(h - 5, s, v * 0.74),
            "L": rgb(h, s * 0.9, v * 0.94), "H": rgb(h + 10, s * 0.45, min(1.0, v * 1.12 + 0.12))}

def accent(h, s, v): return {"a": rgb(h - 12, s * 1.05, v * 0.45), "b": rgb(h, s, v * 0.74), "c": rgb(h + 8, s * 0.8, min(1.0, v * 1.02))}

