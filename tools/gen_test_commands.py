def write(rel, lines):
    p = os.path.join(FN, rel); os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "w", encoding="utf-8", newline="\n") as f: f.write("\n".join(lines).rstrip("\n") + "\n")
def title(k): return " ".join(w.capitalize() for w in k.split("_"))

def items():
    out = []
    for f in sorted(glob.glob(os.path.join(REPO, "resource_pack", "assets", "minecraft", "items", "*.json"))):
        base = os.path.basename(f)[:-5]
        for c in json.load(open(f, encoding="utf-8"))["model"]["cases"]:
            for w in (c["when"] if isinstance(c["when"], list) else [c["when"]]): out.append((base, w[4:]))
    return out

def loot_components():
    """item -> components from the boss loot tables, so a test give matches the real drop."""
    found = {}
    def walk(o, item=None):
        if isinstance(o, dict):
            if o.get("type") == "minecraft:item": item = o.get("name")
            for fn in o.get("functions", []) if isinstance(o.get("functions"), list) else []:
                comps = fn.get("components", {}) if isinstance(fn, dict) and fn.get("function") == "minecraft:set_components" else {}
                cmd = comps.get("minecraft:custom_model_data", {}).get("strings", [])
                if cmd and cmd[0].startswith("slf."): found[cmd[0][4:]] = (item, comps)
            for v in o.values(): walk(v, item)
        elif isinstance(o, list):
            for v in o: walk(v, item)
    for f in glob.glob(os.path.join(REPO, "data_pack", "data", "slf", "loot_table", "*.json")): walk(json.load(open(f, encoding="utf-8")))
    return found

def snbt(v):
    """JSON value -> SNBT for an item component (keys bare when possible, strings double-quoted)."""
    if isinstance(v, bool): return "true" if v else "false"
    if isinstance(v, (int, float)): return json.dumps(v)
    if isinstance(v, str): return json.dumps(v, ensure_ascii=False)
    if isinstance(v, list): return "[" + ",".join(snbt(x) for x in v) + "]"
    if isinstance(v, dict):
        return "{" + ",".join((k if re.fullmatch(r"[A-Za-z0-9_.+-]+", k) else json.dumps(k)) + ":" + snbt(x) for k, x in v.items()) + "}"
    raise TypeError(type(v))

def consumed_on_pickup(name):
    """True when picking the item up teaches a skill and clears the item (skills/learn/* with a matching clear)."""
    for f in glob.glob(os.path.join(FN, "skills", "learn", "*.mcfunction")):
        if f'"slf.{name}"' in open(f, encoding="utf-8").read() and "clear @s" in open(f, encoding="utf-8").read(): return True
    return False

def class_table():
    """class -> (id, display name, colour, prerequisite lineage tags, is starting class), read from the grant files."""
    grant = os.path.join(FN, "class", "grant"); out = {}
    for f in sorted(os.listdir(grant)):
        k = f[:-11]; txt = open(os.path.join(grant, f), encoding="utf-8").read()
        first = next(l for l in txt.splitlines() if l.startswith("execute"))
        m = re.search(r'tellraw @s (\{"text":"You have (?:become|reached) (?:an? )?([^"]+?)\.".*?\})\s*$', txt, re.M)
        out[k] = {"id": int(re.search(r"slf\.class (\d+)", txt).group(1)), "name": m.group(2), "color": json.loads(m.group(1)).get("color", "white"),
                  "prereq": re.findall(r"unless entity @s\[tag=slf\.was_([a-z_]+)\]", first), "t1": "if entity @s[tag=slf.class_chosen]" in first}
    levels = {}
    ev = open(os.path.join(FN, "class", "evolve_apply.mcfunction"), encoding="utf-8").read()
    for cid, lv in re.findall(r"matches (\d+) unless score @s slf\.level matches (\d+)\.\.", ev): levels[int(cid)] = int(lv)
    for c in out.values(): c["level"] = levels.get(c["id"], 1)
    return out

def chain(classes, k, seen=()):
    c = classes[k]
    if c["t1"] or not c["prereq"]: return [k]
    p = next(p for p in c["prereq"] if p in classes and p not in seen)
    return chain(classes, p, seen + (k,)) + [k]

